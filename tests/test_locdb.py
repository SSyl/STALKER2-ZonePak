import hashlib
import struct
import tempfile
import unittest
from pathlib import Path

from zonepak import locdb, uasset

ENTRIES = {'sid_items_Bandage_name': {'en': 'Bandage [Test]', 'de': 'Verband [Test]'}}


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


class ExportBodyTest(unittest.TestCase):
    def test_matches_reference(self):
        self.assertEqual(sha(locdb.export_body(ENTRIES)),
                         '134371ce8e673fc401fb4cfd3b860436154a62043f2db1bc200c28488f900f3a')



class LoadTextTest(unittest.TestCase):
    def test_load_and_reject_unknown_culture(self):
        with tempfile.TemporaryDirectory() as tmp:
            d = Path(tmp)
            (d / 'en.toml').write_text('sid_items_Bandage_name = "Bandage [Test]"\n', encoding='utf-8')
            (d / 'de.toml').write_text('sid_items_Bandage_name = "Verband [Test]"\n', encoding='utf-8')
            self.assertEqual(locdb.load_text(d), ENTRIES)
            (d / 'xx.toml').write_text('a = "b"\n', encoding='utf-8')
            with self.assertRaises(ValueError):
                locdb.load_text(d)



class PackageTest(unittest.TestCase):
    def test_matches_reference(self):
        stem, header, body = uasset.build_locdb_package('TestMod', '1700000000', locdb.export_body(ENTRIES))
        self.assertEqual(stem, 'Autogenerated_1700000000_LocalizationDatabase')
        self.assertEqual((len(header), len(body)), (1521, 109))
        self.assertEqual(sha(header), '85c9a394e027e56e126bf69f03b7e51803fae587d9d6226127bdcf56e1b02961')
        self.assertEqual(sha(body), '0639bb238ce0c62d3dcdd0de1cb83eda8091bd6d436505effdb5f1a0a4892b6c')

    def test_header_offsets_follow_name_length(self):
        export = locdb.export_body(ENTRIES)
        for mod in ('A', 'RealMagazineCapacities'):
            _, header, body = uasset.build_locdb_package(mod, '1700000000', export)
            total = struct.unpack_from('<i', header, 0x1C)[0]
            self.assertEqual(total, len(header))
            self.assertEqual(body[-4:], struct.pack('<I', 0x9E2A83C1))


if __name__ == '__main__':
    unittest.main()
