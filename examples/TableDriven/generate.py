"""Writes TableDriven's patch and text files from table.toml. Run it, then `zonepak check` and `build`."""
import json
import re
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
PATCH = HERE / 'cfg' / 'GameData' / 'ItemPrototypes' / 'TableDriven.cfg'
TEXT = HERE / 'text' / 'en.toml'
# The generated key is written unquoted, so it must be a TOML bare key.
BARE_KEY = re.compile(r'[A-Za-z0-9_-]+')


def magazine_patch(magazines: dict) -> str:
    lines = ['// Generated by generate.py from table.toml.']
    for sid, max_ammo in magazines.items():
        if type(max_ammo) is not int:
            raise SystemExit(f'table.toml: magazines.{sid} must be a whole number')
        lines += [f'{sid} : struct.begin {{bpatch}}',
                  '   Magazine : struct.begin {bpatch}',
                  f'      MaxAmmo = {max_ammo}',
                  '   struct.end',
                  'struct.end']
    return ''.join(line + '\r\n' for line in lines)


def english_text(names: dict) -> str:
    for sid in names:
        if not BARE_KEY.fullmatch(sid):
            raise SystemExit(f'table.toml: names.{sid!r} is not an item SID (letters, digits, _ and - only)')
    lines = ['# Generated by generate.py from table.toml.']
    # For text without U+007F, json.dumps output is also a valid TOML basic string.
    lines += [f'sid_items_{sid}_name = {json.dumps(name, ensure_ascii=False)}' for sid, name in names.items()]
    return ''.join(line + '\n' for line in lines)


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode('utf-8'))
    print(f'wrote {path.relative_to(HERE).as_posix()}')


def main() -> None:
    table = tomllib.loads((HERE / 'table.toml').read_text(encoding='utf-8'))
    patch, text = magazine_patch(table.get('magazines', {})), english_text(table.get('names', {}))
    write(PATCH, patch)
    write(TEXT, text)


if __name__ == '__main__':
    main()
