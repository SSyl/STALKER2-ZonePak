"""Writer for the one legacy package shape ZonePak generates: a mod's localization database.

Layout follows UAssetAPI UAsset.MakeHeader for LegacyFileVersion -8, unversioned, filter-editor-only cooked
packages at UE5 object version ASSETREGISTRY_PACKAGEBUILDDEPENDENCIES (S.T.A.L.K.E.R. 2, UE 5.5.4).
"""
from __future__ import annotations

import struct

from .locdb import CULTURES

PACKAGE_TAG = 0x9E2A83C1
PKG_FLAGS = 0x80002200  # FilterEditorOnly | UnversionedProperties | Cooked
LANGUAGES = ['Arabic', 'ChineseSimplified', 'ChineseTraditional', 'Czech', 'English', 'French', 'German',
             'Italian', 'Japanese', 'Korean', 'Polish', 'PortugalBrazilian', 'Russian', 'Serbian',
             'SpanishEuropean', 'SpanishLatinoAmerican', 'Turkish', 'Ukrainian']
if len(LANGUAGES) != len(CULTURES):
    raise RuntimeError(f'uasset.LANGUAGES has {len(LANGUAGES)} entries, locdb.CULTURES has {len(CULTURES)}')
_SUMMARY_AFTER_FOLDER = 0xB4
_EXPORT_ENTRY = 96


def _fstring(s: str) -> bytes:
    b = s.encode('ascii') + b'\0'
    return struct.pack('<i', len(b)) + b


def build_locdb_package(mod: str, database_id: str, export: bytes) -> tuple[str, bytes, bytes]:
    stem = f'Autogenerated_{database_id}_LocalizationDatabase'
    # The cooked reference packages mark the first 20 names (the languages, then the asset name and path) as
    # referenced from export data.
    names = [f'ELocalizationLanguage::{lang}' for lang in LANGUAGES] + [
        stem, f'/{mod}/{stem}', '/Script/CoreUObject', 'Package', '/Script/Stalker2', 'Class',
        'ModLocalizationDatabaseDataAsset', 'Default__ModLocalizationDatabaseDataAsset']
    index = {n: i for i, n in enumerate(names)}

    def fname(n: str) -> bytes:
        return struct.pack('<ii', index[n], 0)

    name_map = b''.join(_fstring(n) + struct.pack('<I', 0) for n in names)
    imports = b''.join([
        fname('/Script/CoreUObject') + fname('Class') + struct.pack('<i', -3)
        + fname('ModLocalizationDatabaseDataAsset') + struct.pack('<i', 0),
        fname('/Script/Stalker2') + fname('ModLocalizationDatabaseDataAsset') + struct.pack('<i', -3)
        + fname('Default__ModLocalizationDatabaseDataAsset') + struct.pack('<i', 0),
        fname('/Script/CoreUObject') + fname('Package') + struct.pack('<i', 0)
        + fname('/Script/Stalker2') + struct.pack('<i', 0),
    ])

    folder = _fstring(f'/{mod}/{stem}')
    name_offset = 0x20 + len(folder) + _SUMMARY_AFTER_FOLDER
    import_offset = name_offset + len(name_map)
    export_offset = import_offset + len(imports)
    depends_offset = export_offset + _EXPORT_ENTRY
    asset_registry_offset = depends_offset + 4
    preload_offset = asset_registry_offset + 4
    header_size = preload_offset + 8

    export_entry = b''.join([
        struct.pack('<iiii', -1, 0, -2, 0),          # class, super, template, outer
        fname(stem),
        struct.pack('<I', 3),                         # RF_Public | RF_Standalone
        struct.pack('<qq', len(export), header_size),
        struct.pack('<iiiiIiii', 0, 0, 0, 0, 0, 0, 0, 0),
        struct.pack('<iiiii', 0, 0, 0, 2, 0),         # preload dependencies: 2 serialize-before-create
    ])
    summary = b''.join([
        struct.pack('<Iiiiiiii', PACKAGE_TAG, -8, 0, 0, 0, 0, 0, header_size),
        folder,
        struct.pack('<I', PKG_FLAGS),
        struct.pack('<ii', len(names), name_offset),
        struct.pack('<ii', 0, import_offset),         # soft object paths
        struct.pack('<ii', 0, 0),                     # gatherable text
        struct.pack('<ii', 1, export_offset),
        struct.pack('<ii', 3, import_offset),
        struct.pack('<i', depends_offset),
        struct.pack('<iii', 0, 0, 0),                 # soft package references, searchable names
        struct.pack('<i', 0),                         # thumbnail table
        bytes(16),                                    # package guid
        struct.pack('<iii', 1, 1, len(names)),        # one generation
        struct.pack('<HHHIi', 0, 0, 0, 0, 0),         # saved-by engine version, empty branch
        struct.pack('<HHHIi', 0, 0, 0, 0, 0),         # compatible-with engine version
        struct.pack('<IiIi', 0, 0, 0, 0),             # compression, chunks, source, packages to cook
        struct.pack('<i', asset_registry_offset),
        struct.pack('<q', header_size + len(export)),  # bulk data start
        struct.pack('<ii', 0, 0),                     # world tile info, chunk ids
        struct.pack('<ii', 2, preload_offset),
        struct.pack('<i', len(LANGUAGES) + 2),        # names referenced from export data
        struct.pack('<q', -1),                        # payload toc
        struct.pack('<i', -1),                        # data resources
    ])
    tail = struct.pack('<iiii', 0, 0, -1, -2)         # depends map, asset registry, preload -1 and -2
    header = summary + name_map + imports + export_entry + tail
    assert len(summary) == name_offset and len(header) == header_size
    return stem, header, export + struct.pack('<I', PACKAGE_TAG)
